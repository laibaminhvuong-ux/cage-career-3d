import assert from 'node:assert/strict';
import * as THREE from '../web/vendor/three.module.min.js';
import { RingsideLED } from '../web/ringside-led3d.js';
const calls=[];
const ctx={fillRect(){},fillText(text){calls.push(text);}};
globalThis.document={createElement:()=>({getContext:()=>ctx})};
const scene=new THREE.Scene(),led=new RingsideLED(scene);
assert.equal(led.root.children.length,7);
assert(led.root.children.every(b=>!(b.position.x < -6 && Math.abs(b.position.z)<1)), 'Walkout aisle stays clear');
const fight={org:'Iron Cage',round:0,rounds:3,finished:true,winner:'player'};
const before=JSON.stringify(fight);led.reset(fight);
assert.equal(led.label,'FIGHT NIGHT','Restore never reveals a future result');
const version=led.texture.version;led.reset(fight);assert.equal(led.texture.version,version,'Identical screen is not uploaded again');
led.event({type:'info',side:'n',text:'Round 3'});assert.equal(led.label,'FINAL ROUND');
led.event({type:'kd',side:'p'});assert.equal(led.label,'KNOCKDOWN');
led.update(1);assert(led.trim.opacity>0.25&&led.trim.opacity<0.8);
led.update(3);assert.equal(led.label,'FINAL ROUND');
led.event({type:'subatt',side:'o'});assert.equal(led.label,'SUBMISSION THREAT');
led.event({type:'round',side:'n'});led.update(20);assert.equal(led.label,'BACK TO YOUR CORNER');
led.event({type:'finish',side:'n',text:'The judges score it 29-28.'});assert.equal(led.label,'OFFICIAL DECISION');
led.reset({org:'GFC',round:1,rounds:5});assert.equal(led.label,'ROUND 1');
assert.equal(JSON.stringify(fight),before,'Presentation never mutates fight state');
const v=led.texture.version;for(let i=0;i<600;i++)led.update(1/60);
assert.equal(led.texture.version,v,'No per-frame canvas uploads');
assert.equal(scene.children.filter(x=>x.isLight).length,0,'No additional lights');
console.log('PASS: 7 pooled LED boards, clear entrance aisle, round/knockdown/submission/decision reactions, smooth decay, restore without spoilers, no fight mutation or per-frame texture uploads');
