export const CURRENT = UPDATES[0].version;
const AUTO_KEY = "cc3d_whatsnew_auto";
const SEEN_KEY = "cc3d_whatsnew_seen";

/** Whether What's new opens when the game starts (on unless the player switched it off). */
export function whatsNewAuto() {
  try { return localStorage.getItem(AUTO_KEY) !== "off"; } catch { return true; }
}
export function setWhatsNewAuto(on) {
  try { localStorage.setItem(AUTO_KEY, on ? "on" : "off"); } catch { /* ignore */ }
}
/** The newest version the player had already seen (versions after it are marked NEW). */
export function lastSeen() {
  try { return localStorage.getItem(SEEN_KEY) || ""; } catch { return ""; }
}
export function markSeen() {
  try { localStorage.setItem(SEEN_KEY, CURRENT); } catch { /* ignore */ }
}

const newer = (a, b) => {
  const pa = a.split(".").map(Number), pb = (b || "0").split(".").map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) if ((pa[i] || 0) !== (pb[i] || 0)) return (pa[i] || 0) > (pb[i] || 0);
  return false;
};

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

/** The screen: every version, the ones you haven't seen marked NEW, and the startup switch. */
export function whatsNewHtml(seen = lastSeen(), auto = whatsNewAuto()) {
  return `<div class="whatsnew">
    <h2>📰 What's new</h2>
    <p class="muted">Version ${esc(CURRENT)} · everything we've added, newest first.</p>
    ${UPDATES.map((u, i) => `<section class="wn-version ${i === 0 ? "latest" : ""}">
      <div class="wn-head"><b>v${esc(u.version)}</b> <span class="wn-title">${esc(u.title)}</span>
        ${newer(u.version, seen) ? `<span class="badge gold">NEW</span>` : ""}<span class="muted wn-date">${esc(u.date)}</span></div>
      <ul>${u.items.map((t) => `<li>${esc(t)}</li>`).join("")}</ul>
    </section>`).join("")}
    <label class="wn-auto"><input type="checkbox" data-whatsnewauto ${auto ? "checked" : ""}> Show What's new when the game opens</label>
    <div class="btn-row"><button class="btn primary big" data-whatsnewdone>Let's go</button></div>
  </div>`;
}
